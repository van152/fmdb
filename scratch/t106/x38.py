import pathlib,sys,struct
sys.stdout.reconfigure(encoding='utf-8')
D=pathlib.Path('scratch/t106/out')
def hx(x): return ' '.join(f'{c:02x}' for c in x)
b=(D/'payload_summary.bin').read_bytes()
print('len',len(b))
print('hdr0-40:',hx(b[:40]))
print('u32@8',struct.unpack_from('<I',b,8)[0])
print('ids 12..40:',[struct.unpack_from('<I',b,12+4*i)[0] for i in range(7)])
print('40..120:',hx(b[40:120]))
sep=b'\xff\xff\xff\xff\x03'
offs=[];i=b.find(sep)
while i>=0: offs.append(i); i=b.find(sep,i+1)
print('nsep',len(offs),'first',offs[:4],'last',offs[-3:])
print('first body:',hx(b[40:offs[0]]), 'len',offs[0]-40)
print('body1:',hx(b[offs[0]+5:offs[1]]))
print('body2:',hx(b[offs[1]+5:offs[2]]))
print('last body:',hx(b[offs[-1]+5:offs[-1]+5+40]))
print('after last sep -> end len',len(b)-(offs[-1]+5))
print(hx(b[offs[-1]:offs[-1]+60]))
# tail pair check
end=len(b)
print('tail21:',hx(b[-21:]))
