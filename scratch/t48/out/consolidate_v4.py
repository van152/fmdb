class CheckFailure(Exception):
    pass


def require(condition: bool, message: str) -> None:
    if not condition:
        raise CheckFailure(message)


def rel(path: str) -> Path:
    return ROOT / Path(path)


def read_json(path: str | Path) -> Any:
    target = path if isinstance(path, Path) else rel(path)
    return json.loads(target.read_text(encoding="utf-8"))


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def canonical_sha256(value: Any) -> str:
    raw = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return sha256_bytes(raw)


def source_artifact(path: str) -> dict[str, Any]:
    target = rel(path)
    if not target.is_file():
        raise CheckFailure(f"missing source artifact: {path}")
    return {"path": path, "sha256": sha256_file(target), "bytes": target.stat().st_size}


def load_v3_baseline() -> tuple[dict[str, Any], bytes]:
    source = V3_JSON if V3_JSON.is_file() else PUBLIC_JSON
    raw = source.read_bytes()
    if sha256_bytes(raw) != V3_JSON_SHA256:
        raise CheckFailure("v3 JSON baseline SHA-256 mismatch; refusing to replace an unknown baseline")
    baseline = json.loads(raw.decode("utf-8"))
    require(baseline.get("schema_version") == 3 and baseline.get("generated_by") == "t45", "expected t45 schema v3")
    require(len(baseline.get("tables", [])) == 8, "v3 baseline must contain exactly eight numeric tables")
    require(sum(len(table.get("fields", [])) for table in baseline["tables"]) == 52, "v3 baseline L3 count changed")
    require(sum(len(table.get("held_fields", [])) for table in baseline["tables"]) == 16, "v3 baseline held count changed")
    require(len(baseline.get("negative_regressions", [])) == 4, "v3 baseline negative regression count changed")
    return baseline, raw


def load_v3_markdown() -> tuple[str, bytes]:
    source = V3_MD if V3_MD.is_file() else PUBLIC_MD
    raw = source.read_bytes()
    if sha256_bytes(raw) != V3_MD_SHA256:
        raise CheckFailure("v3 Markdown baseline SHA-256 mismatch; refusing to replace an unknown baseline")
    text = raw.decode("utf-8")
    require("Generated by t45:" in text and "Accepted L3 business fields: 52" in text, "expected t45 v3 Markdown")
    return text, raw


