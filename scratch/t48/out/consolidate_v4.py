def summarize_occurrence(view: str, record: dict[str, Any]) -> dict[str, Any]:
    code = record["code"]
    grade = record["grade"]
    encoding = record["encoding"]
    item: dict[str, Any] = {
        "view": view,
        "schema_idx": record["schema_idx"],
        "code": code,
        "schema": copy.deepcopy(record["schema"]),
        "grade": grade,
        "encoding": encoding,
        "source_task": "t44",
        "source_record_sha256": canonical_sha256(record),
        "source_record": copy.deepcopy(record),
        "wire_coordinates": [],
    }
    if grade == "L3":
        item["status"] = "accepted_L3"
        if code in {"affl", "ismc"}:
            lanes = []
            for endpoint in ("A", "B"):
                lane = record["endpoint_slots"][endpoint]
                lanes.append({
                    "endpoint": endpoint,
                    "wire_offset": lane["row_offset"],
                    "width_bytes": lane["width"],
                    "actual_ordinal_hits": lane["actual_ordinal_hits"],
                    "first": copy.deepcopy(lane["first"]),
                    "wrong_uid_row_misses": lane["wrong_uid_row_misses"],
                })
            item["endpoint_lanes"] = lanes
            item["coordinate_note"] = (
                "Viewer-relative derived field over both endpoint lanes, not one stored slot. "
                + ("For affl, if current club == A select B, otherwise select A." if code == "affl" else
                   "For ismc, true exactly when current club == A; this is not a stored bit.")
                + " Applies only to links registered to the current club; fixup may filter rows before view access."
            )
        elif encoding == "bit":
            bit_index = record["bit_index"]
            item["wire_coordinates"] = [{
                "wire_offset": record["row_offset"],
                "width_bytes": record["width"],
                "storage": "shared_u32_bitmask",
                "bit_index": bit_index,
                "bit_mask_u32": record["bit_mask_u32"],
            }]
            item["bit_index"] = bit_index
            item["bit_mask_u32"] = record["bit_mask_u32"]
            item["coordinate_note"] = (
                "One of 20 bool occurrences sharing a single u32 transfer at wire +5..+8; "
                "the bit mask identifies this flag and is not an independent byte slot."
            )
        else:
            item["wire_coordinates"] = [{
                "wire_offset": record["row_offset"],
                "width_bytes": record["width"],
            }]
            if encoding == "date":
                item["coordinate_note"] = record["decoded"]
            elif code in {"fri%", "pwgp"}:
                item["coordinate_note"] = (
                    f"Signed i8 at wire +{record['row_offset']}; -1 is omitted/unset "
                    f"({record.get('minus_one_count')} rows); live values use schema domain [0,100]."
                )
                if code == "pwgp":
                    item["raw_zero_count"] = next((count for value, count in record["profile"]["top"] if value == 0), 0)
    elif grade == "runtime_only_no_wire_slot":
        item["status"] = "runtime_only_no_wire_slot"
        item["runtime_coordinate"] = {
            "object": "Cvfl wrapper",
            "offset": 8,
            "interpretation": "validation reason, not persisted wire data",
        }
        item["coordinate_note"] = (
            "Runtime-only clfr validator result on the Cvfl wrapper +8; no wire slot and excluded from L3 counts. "
            "The wrapper is appended without a validation-success-only gate."
        )
        item["domain"] = copy.deepcopy(record.get("domain"))
        item["first_counterexample"] = record.get("first_counterexample")
        item["validator_written_values"] = [1, 2, 3, 4, 5, 6]
        item["copy_append_requires_validation_success"] = False
    else:
        item["status"] = "held"
        item["candidate_coordinate"] = {
            "wire_offset": record["candidate_row_offset"],
            "width_bytes": record["width"],
            "disposition": "candidate only; not promoted",
        }
        item["first_counterexample"] = copy.deepcopy(record.get("first_counterexample"))
        item["domain"] = copy.deepcopy(record.get("domain"))
        item["profile"] = copy.deepcopy(record.get("profile"))
        item["coordinate_note"] = {
            "type": "Held: raw value 21 is absent from the CAfT domain; 609 rows conflict. First counterexample retained.",
            "yfee": "Held: 8,984 raw -1 values conflict with schema [0,1000000000]; no sentinel is inferred.",
            "msls": "Held: all 9,261 values are -1; no live value establishes the schema domain.",
        }[code]
    return item


def compute_wire_slots(views: list[dict[str, Any]]) -> list[dict[str, Any]]:
    slots: dict[tuple[int, int], dict[str, Any]] = {}
    for view in views:
        for occurrence in view["occurrences"]:
            if occurrence["grade"] != "L3":
                continue
            coords = occurrence["endpoint_lanes"] if occurrence["code"] in {"affl", "ismc"} else occurrence["wire_coordinates"]
            for coord in coords:
                key = (coord.get("wire_offset", coord.get("wire_offset")), coord["width_bytes"])
                entry = slots.setdefault(key, {"wire_offset": key[0], "width_bytes": key[1], "codes": [], "schema_indices": []})
                if occurrence["code"] not in entry["codes"]:
                    entry["codes"].append(occurrence["code"])
                if occurrence["schema_idx"] not in entry["schema_indices"]:
                    entry["schema_indices"].append(occurrence["schema_idx"])
                if "bit_index" in coord:
                    entry.setdefault("bit_indices", []).append(coord["bit_index"])
    ordered = []
    for key in sorted(slots):
        entry = slots[key]
        if key == (5, 4):
            entry["storage"] = "one shared u32 bitmask word; 20 named flags"
            entry["bit_indices"] = sorted(set(entry.get("bit_indices", [])))
        elif key in {(0, 4), (9, 4)}:
            entry["storage"] = "CLUB_LINK endpoint lane"
        else:
            entry["storage"] = "independent scalar wire lane"
        ordered.append(entry)
    return ordered


