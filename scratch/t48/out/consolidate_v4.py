def validate_schema(schema: dict[str, Any], baseline: dict[str, Any], report: str, data: dict[str, Any]) -> None:
    require(schema.get("schema_version") == 4 and schema.get("generated_by") == "t48", "schema is not v4")
    require(schema.get("tables") == baseline.get("tables"), "v3 numeric table records changed")
    require(schema.get("negative_regressions") == baseline.get("negative_regressions"), "v3 negative regressions changed")
    require(schema.get("binary_provenance") == baseline.get("binary_provenance"), "v3 binary provenance changed")
    coverage = schema["coverage"]
    require((coverage["club_tables"], coverage["club_L3_fields"], coverage["club_L3_occurrences"],
             coverage["club_L3_unique_wire_fields"], coverage["held_fields"], coverage["held_fields_v3_numeric_tables"],
             coverage["negative_regressions"], coverage["L4"]) == (8, 52, 94, 59, 21, 16, 4, 0), "v4 dual coverage totals mismatch")
    require(len(schema["club_auxiliary_sources"]) == 1 and len(schema["club_auxiliary_sources"][0]["views"]) == 2,
            "CLUB_LINK source/view count mismatch")
    require(schema["nation_data_side_status"]["server_only_fields_promoted"] == 0, "nation server-only fields were promoted")
    require(schema["nation_data_side_status"]["evidence_levels"] == {"L1": True, "L2": True, "L3": 0, "L4": 0},
            "nation L1/L2/L3/L4 status mismatch")
    require("## t48 Incremental Addendum" in report and "club_L3_unique_wire_fields`: 59" in report,
            "v4 Markdown coverage addendum missing")


def selftest() -> tuple[dict[str, Any], str, dict[str, Any], bytes, str, dict[str, Any]]:
    baseline, baseline_raw = load_v3_baseline()
    baseline_md, _ = load_v3_markdown()
    data = check_inputs()
    schema, report = build_schema(baseline, baseline_raw, baseline_md, data)
    validate_schema(schema, baseline, report, data)
    return schema, report, baseline, baseline_raw, baseline_md, data


def write_outputs(schema: dict[str, Any], report: str, baseline_raw: bytes, baseline_md: str) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    if V3_JSON.exists():
        require(sha256_file(V3_JSON) == V3_JSON_SHA256, "existing v3 JSON snapshot SHA-256 mismatch")
    else:
        V3_JSON.write_bytes(baseline_raw)
    baseline_md_raw = baseline_md.encode("utf-8")
    if V3_MD.exists():
        require(sha256_file(V3_MD) == V3_MD_SHA256, "existing v3 Markdown snapshot SHA-256 mismatch")
    else:
        V3_MD.write_bytes(baseline_md_raw)

    expected_json = (json.dumps(schema, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
    current_json = OUT_JSON.read_bytes() if OUT_JSON.exists() else baseline_raw
    current_md = OUT_MD.read_bytes() if OUT_MD.exists() else baseline_md_raw
    if current_json not in (baseline_raw, expected_json):
        try:
            previous = json.loads(current_json.decode("utf-8"))
        except json.JSONDecodeError as exc:
            raise CheckFailure("public JSON is not a recognized v3/v4 schema") from exc
        require(previous.get("schema_version") == 4 and previous.get("generated_by") == "t48" and
                previous.get("tables") == schema["tables"] and
                previous.get("negative_regressions") == schema["negative_regressions"],
                "public JSON is neither the frozen v3 baseline nor an evolvable t48 output")
    expected_md = report.encode("utf-8")
    if current_md not in (baseline_md_raw, expected_md):
        previous_md = current_md.decode("utf-8")
        require("Generated by t48:" in previous_md and "## t48 Incremental Addendum" in previous_md,
                "public Markdown is neither the frozen v3 baseline nor an evolvable t48 report")
    OUT_JSON.write_bytes(expected_json)
    OUT_MD.write_bytes(expected_md)
    print(f"WROTE {OUT_JSON.relative_to(ROOT)}")
    print(f"WROTE {OUT_MD.relative_to(ROOT)}")
    print(f"SNAPSHOT {V3_JSON.relative_to(ROOT)}")
    print(f"SNAPSHOT {V3_MD.relative_to(ROOT)}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Incrementally append accepted t44 CLUB_LINK and t46 nation data-side evidence to schema v3.")
    parser.add_argument("--selftest", action="store_true", help="build in memory and validate counts, coordinates, provenance, and v3 preservation")
    args = parser.parse_args(argv)
    try:
        schema, report, baseline, baseline_raw, baseline_md, _ = selftest()
        if args.selftest:
            print("SELFTEST PASS: v3 eight tables verbatim; 94 scoped L3 occurrences; 59 unique-wire count; CLUB_LINK closure/coordinate policies; held/runtime exclusions; t46 L3=0")
            return 0
        write_outputs(schema, report, baseline_raw, baseline_md)
        print("t48 schema v4 build complete")
        return 0
    except CheckFailure as exc:
        print(f"CHECK FAILED: {exc}", file=sys.stderr)
        return 1
    except (OSError, json.JSONDecodeError, KeyError, TypeError, ValueError) as exc:
        print(f"FATAL: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
