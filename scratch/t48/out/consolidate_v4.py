def coordinate_text(item: dict[str, Any]) -> str:
    code = item["code"]
    if code in {"affl", "ismc"}:
        detail = "wire +0/4 A, +9/4 B; "
        return detail + ("viewer club==A ? B : A" if code == "affl" else "derived true iff viewer club==A")
    if item["status"] == "runtime_only_no_wire_slot":
        return "no wire slot; Cvfl wrapper +8 runtime-only"
    if item["status"] == "held":
        coord = item["candidate_coordinate"]
        return f"candidate +{coord['wire_offset']}/{coord['width_bytes']}B; held, not promoted"
    if item.get("encoding") == "bit":
        coord = item["wire_coordinates"][0]
        return f"u32 +5..+8; bit {coord['bit_index']}, mask 0x{coord['bit_mask_u32']:08x}"
    coords = item["wire_coordinates"]
    return ", ".join(f"+{coord['wire_offset']}/{coord['width_bytes']}B" for coord in coords)


